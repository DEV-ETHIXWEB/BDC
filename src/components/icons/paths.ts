const n = (v: number) => String(Math.round(v * 100) / 100);
// circle / rounded-rect path helpers (keep geometry exact)
const c = (cx: number, cy: number, r: number) => `M${n(cx - r)} ${n(cy)}a${r} ${r} 0 1 0 ${n(2 * r)} 0a${r} ${r} 0 1 0 ${n(-2 * r)} 0z`;
const rr = (x: number, y: number, w: number, h: number, r: number) =>
  `M${n(x + r)} ${y}h${n(w - 2 * r)}a${r} ${r} 0 0 1 ${r} ${r}v${n(h - 2 * r)}a${r} ${r} 0 0 1-${r} ${r}h${n(-(w - 2 * r))}a${r} ${r} 0 0 1-${r}-${r}v${n(-(h - 2 * r))}a${r} ${r} 0 0 1 ${r}-${r}z`;

// rotate/scale/translate absolute-coordinate paths (M L C Q H V Z only)
function xf(path: string, rot: number, cx: number, cy: number, s = 1, dx = 0, dy = 0) {
  const a = (rot * Math.PI) / 180, co = Math.cos(a), si = Math.sin(a);
  const P = (x: number, y: number) => {
    const X = x - cx, Y = y - cy;
    return `${n(cx + dx + s * (X * co - Y * si))} ${n(cy + dy + s * (X * si + Y * co))}`;
  };
  const tk = path.match(/[a-zA-Z]|-?\d*\.?\d+/g) ?? [];
  let out = '', i = 0, cmd = '';
  const num = () => parseFloat(tk[i++]);
  while (i < tk.length) {
    if (/[a-zA-Z]/.test(tk[i])) cmd = tk[i++];
    if (cmd === 'Z') { out += 'Z'; continue; }
    const cnt = cmd === 'C' ? 3 : cmd === 'Q' ? 2 : 1;
    out += cmd;
    for (let k = 0; k < cnt; k++) { const x = num(), y = num(); out += (k ? ' ' : '') + P(x, y); }
  }
  return out;
}
const xp = (pt: [number, number], rot: number, cx: number, cy: number, s = 1, dx = 0, dy = 0): [number, number] => {
  const a = (rot * Math.PI) / 180, X = pt[0] - cx, Y = pt[1] - cy;
  return [Math.round((cx + dx + s * (X * Math.cos(a) - Y * Math.sin(a))) * 100) / 100, Math.round((cy + dy + s * (X * Math.sin(a) + Y * Math.cos(a))) * 100) / 100];
};


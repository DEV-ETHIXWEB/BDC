export type IconName = keyof typeof ICONS;

/** One flat layer list, shared by Icon.astro and react/Icon.tsx so both render identically. */
export function iconLayers(name: IconName, variant: IconVariant = 'line'): IconLayer[] {
  const i = ICONS[name] as IconDef;
  const L: IconLayer[] = [];
  i.f?.forEach((d) => L.push({ k: 'f', d }));
  if (variant === 'tile') i.t?.forEach((d) => L.push({ k: 't', d }));
  i.p.forEach((d) => L.push({ k: 'p', d }));
  i.a?.forEach((d) => L.push({ k: 'a', d }));
  i.d?.forEach(([cx, cy, r]) => L.push({ k: 'd', cx, cy, r: r ?? 0.9 }));
  return L;
}
